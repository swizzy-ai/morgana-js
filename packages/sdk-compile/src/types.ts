/**
 * Project type generation — what `morgana types` runs, and what every build
 * runs as a side effect so the editor never lags the code.
 *
 *   .morgana/types/registry.d.ts   ActionsRegistry — `ctx.actions.run` typed from each action's `Contract`
 *   .morgana/objects.d.ts          ObjectRegistry — `ctx.objects.<name>` typed from each server object
 *   .morgana/ui.d.ts               UiApi — `ctx.ui.<name>` typed from each custom object in src/objects
 *
 * Both are scanned statically: no action runs, no network. A project picks them
 * up through its tsconfig `include` of `.morgana/**\/*.d.ts` (`morgana init`
 * writes that tsconfig).
 *
 * Files are written only when their contents change. `morgana dev` watches the
 * project, and rewriting an identical file on every compile would be a
 * recompile loop for any watcher that does not know to ignore `.morgana/`.
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { generateRegistry, resolveActionsDirs, type GeneratedRegistry } from '@morgana/sdk/generator'

import { discoverCustomObjects } from './custom-objects'
import { scanProject } from './extract'
import type { CustomObjectDecl } from './ir'
import { compileServerObjects, objectKey, objectTypesDts, type CompiledServerObject } from './objects-compile'

export interface GenerateTypesOptions {
  dir: string
  actionsDirs?: string[]
}

export interface GeneratedTypes {
  /** Actions whose `Contract` is now typed at every call site. */
  actions: string[]
  /** Actions scanned without a `Contract` export — they type as unknown. */
  untypedActions: string[]
  /** Server objects, by their `ctx.objects` key. */
  objects: string[]
  /** Custom UI objects, by their `ctx.ui` key. */
  customObjects: string[]
  /** Files whose contents changed on this run (relative to the project). */
  written: string[]
  warnings: string[]
}

/** Write `file` only when its contents differ. Returns true when it wrote. */
export function writeIfChanged(file: string, contents: string): boolean {
  try {
    if (fs.readFileSync(file, 'utf8') === contents) return false
  } catch {
    /* missing — write it */
  }
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, contents)
  return true
}

/**
 * Write `.morgana/objects.d.ts` for already-compiled objects. Always written,
 * including when there are none, so a deleted object leaves the registry rather
 * than lingering as a type that resolves to a missing file.
 */
export function writeObjectTypes(dir: string, objects: CompiledServerObject[]): boolean {
  return writeIfChanged(path.join(dir, '.morgana', 'objects.d.ts'), objectTypesDts(dir, objects))
}

/** Every file under the action dirs, with its mtime — the registry's real input. */
function actionsStamp(opts: GenerateTypesOptions): string {
  const parts: string[] = []
  const walk = (d: string) => {
    let items: fs.Dirent[]
    try {
      items = fs.readdirSync(d, { withFileTypes: true })
    } catch {
      return
    }
    for (const item of items) {
      const full = path.join(d, item.name)
      if (item.isDirectory()) walk(full)
      else parts.push(`${full}:${fs.statSync(full).mtimeMs}`)
    }
  }
  for (const d of resolveActionsDirs({ dir: opts.dir, actionsDirs: opts.actionsDirs })) walk(d)
  return parts.sort().join('\n')
}

/**
 * The last registry per project, so `morgana dev` — one process, a compile per
 * save — only pays for a TypeScript program when an action actually changed.
 */
const registryCache = new Map<string, { stamp: string; result: GeneratedRegistry }>()

/**
 * Regenerate the action registry. `generateRegistry` always writes, so render
 * into a scratch dir and copy across only on change.
 */
function writeRegistry(opts: GenerateTypesOptions) {
  const target = path.join(opts.dir, '.morgana', 'types', 'registry.d.ts')
  const stamp = actionsStamp(opts)
  const cached = registryCache.get(opts.dir)
  if (cached && cached.stamp === stamp && fs.existsSync(target)) return { result: cached.result, wrote: false }
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'morgana-types-'))
  try {
    const result = generateRegistry({ dir: opts.dir, actionsDirs: opts.actionsDirs, outDir: scratch })
    registryCache.set(opts.dir, { stamp, result })
    return { result, wrote: writeIfChanged(target, result.dts) }
  } finally {
    fs.rmSync(scratch, { recursive: true, force: true })
  }
}

/**
 * `.morgana/ui.d.ts` — `ctx.ui.<name>` for each custom object in `src/objects/`.
 * Discovery is the compiler's own source read, so a name the build accepts is
 * the name the types carry.
 */
export function uiTypesDts(dir: string, decls: CustomObjectDecl[]): string {
  const outDir = path.join(dir, '.morgana')
  const lines = [
    '// Generated by `morgana types` / `morgana build` — do not edit.',
    "import type { CustomCreatable } from '@morgana/sdk'",
  ]
  const entries: string[] = []
  decls.forEach((d, i) => {
    const spec = `./${path.relative(outDir, d.file).replace(/\\/g, '/').replace(/\.(ts|tsx|mts|js|mjs)$/, '')}`
    lines.push(`import type __c${i} from ${JSON.stringify(spec)}`)
    entries.push(`    ${JSON.stringify(objectKey(d.name))}: CustomCreatable<typeof __c${i}>`)
  })
  lines.push("declare module '@morgana/sdk' {", '  interface UiApi {', ...entries, '  }', '}', '')
  return lines.join('\n')
}

export interface RefreshedTypes {
  registry: GeneratedRegistry | null
  customObjects: string[]
  written: string[]
}

/**
 * Write all three type files for a project whose server objects are already
 * compiled. Never throws — a build must not fail over its editor types; a
 * problem becomes a warning.
 */
export function refreshProjectTypes(
  opts: GenerateTypesOptions,
  serverObjects: CompiledServerObject[],
  warnings: string[],
): RefreshedTypes {
  const { dir } = opts
  const written: string[] = []
  const attempt = (what: string, fn: () => void) => {
    try {
      fn()
    } catch (err) {
      warnings.push(`${what} types not regenerated: ${(err as Error).message}`)
    }
  }

  attempt('server object', () => {
    if (writeObjectTypes(dir, serverObjects)) written.push('.morgana/objects.d.ts')
  })

  let customObjects: string[] = []
  attempt('custom object', () => {
    const decls = discoverCustomObjects(dir, [])
    customObjects = decls.map((d) => objectKey(d.name))
    if (writeIfChanged(path.join(dir, '.morgana', 'ui.d.ts'), uiTypesDts(dir, decls))) written.push('.morgana/ui.d.ts')
  })

  let registry: GeneratedRegistry | null = null
  attempt('action', () => {
    const r = writeRegistry(opts)
    registry = r.result
    if (r.wrote) written.push('.morgana/types/registry.d.ts')
  })

  return { registry, customObjects, written }
}

/** Generate every project type file. Never runs project code. */
export async function generateTypes(opts: GenerateTypesOptions): Promise<GeneratedTypes> {
  const warnings: string[] = []
  const scan = scanProject({ dir: opts.dir, actionsDirs: opts.actionsDirs })
  const libraries = (scan.config as { libraries?: string[] }).libraries ?? []
  const objects = await compileServerObjects(opts.dir, libraries, warnings)
  const r = refreshProjectTypes(opts, objects, warnings)

  return {
    actions: r.registry?.entries.map((e) => e.name) ?? [],
    untypedActions: r.registry?.untyped ?? [],
    objects: objects.map((o) => objectKey(o.meta.name)),
    customObjects: r.customObjects,
    written: r.written,
    warnings,
  }
}
