/** CSS for the animation and behavior words `make()` can set. */
function tokenClassRules(ir: ProjectIR): string[] {
  const used = new Set<string>()
  for (const node of ir.objects.values()) {
    const a = node.props['animate']
    if (typeof a === 'string') used.add(`morgana-anim-${a.replace(/-/g, '_')}`)
    const b = node.props['behavior']
    if (typeof b === 'string') used.add(`morgana-bh-${b}`)
  }
  if (!used.size) return []
  const all = animationClasses()
  const out: string[] = []
  for (const cls of used) {
    const decls = all[cls]
    if (decls) out.push(`.${cls}{${decls}}`)
  }
  return out
}

/** Every object inside a list's row template → the template's root. */
export function templateRows(ir: ProjectIR): Map<string, string> {
  const out = new Map<string, string>()
  for (const node of ir.objects.values()) {
    const root = node.contentTemplateId
    if (!root || out.has(root)) continue
    const stack = [root]
    while (stack.length) {
      const id = stack.pop() as string
      if (out.has(id)) continue
      out.set(id, root)
      for (const c of ir.objects.get(id)?.children ?? []) stack.push(c)
    }
  }
  return out
}

