/**
 * Input behaviors: switches, checkboxes, radios, alerts, badges.
 *
 * Split from the overlay handler so the dialog's early-returns cannot swallow
 * these, and vice versa.
 */
export function inputBehaviors(): string[] {
  return [
    'function syncTags(host){',
    '  var tags = [];',
    '  var nodes = host.querySelectorAll("[data-part=\\"tag\\"]");',
    '  for(var i=0;i<nodes.length;i++){ tags.push(nodes[i].getAttribute("data-tag")||nodes[i].textContent||""); }',
    '  host.setAttribute("data-value", tags.join(","));',
    '  dispatchPageEvent("changed", host.getAttribute("data-entity")||"", host, {value:tags});',
    '}',
    'function openEditable(host, draft){',
    '  host.setAttribute("data-editing","true");',
    '  var pv = host.querySelector("[data-part=\\"preview\\"]");',
    '  if(pv) pv.setAttribute("hidden","");',
    '  var ed = host.querySelector("input[data-part=\\"editor\\"]");',
    '  if(ed){ ed.removeAttribute("hidden"); if(draft!==undefined) ed.value = draft; ed.focus(); if(ed.select) ed.select(); }',
    '}',
    'function closeEditable(host, commit){',
    '  var ed = host.querySelector("input[data-part=\\"editor\\"]");',
    '  var pv = host.querySelector("[data-part=\\"preview\\"]");',
    '  var val = ed ? ed.value : (host.getAttribute("data-value")||"");',
    '  if(commit){',
    '    host.setAttribute("data-value", val);',
    '    if(pv) pv.textContent = val;',
    '    dispatchPageEvent("changed", host.getAttribute("data-entity")||"", ed, {value:val});',
    '    dispatchPageEvent("submitted", host.getAttribute("data-entity")||"", ed, {value:val});',
    '  } else if(ed){',
    '    ed.value = host.getAttribute("data-value")||"";',
    '    dispatchPageEvent("cancelled", host.getAttribute("data-entity")||"", ed, {});',
    '  }',
    '  host.setAttribute("data-editing","false");',
    '  if(pv) pv.removeAttribute("hidden");',
    '  if(ed) ed.setAttribute("hidden","");',
    '}',
    'function paintFiles(host){',
    '  var input = host.querySelector("input[data-part=\\"file-input\\"]");',
    '  var list = host.querySelector("[data-part=\\"file-list\\"]");',
    '  if(!list) return [];',
    '  var files = input && input.files ? Array.prototype.slice.call(input.files) : [];',
    '  var out = "";',
    '  for(var i=0;i<files.length;i++){',
    '    var f = files[i];',
    '    var nm = String(f.name).replace(/&/g,"&amp;").replace(/</g,"&lt;");',
    '    out += "<div data-part=\\"file\\"><span data-part=\\"file-name\\">"+nm+"</span><span data-part=\\"file-size\\">"+f.size+" B</span></div>";',
    '  }',
    '  list.innerHTML = out;',
    '  return files.map(function(f){ return {name:f.name,size:f.size,type:f.type}; });',
    '}',
    'document.addEventListener("click", function(e){',
    '  var ax = e.target && e.target.closest ? e.target.closest("[data-kind=\\"alert\\"] [data-part=\\"dismiss\\"]") : null;',
    '  if(ax){ var al=ax.closest("[data-kind=\\"alert\\"]"); if(al){al.style.display="none";return;} }',
    '  var rm = e.target && e.target.closest ? e.target.closest("[data-part=\\"remove\\"]") : null;',
    '  if(rm){ var badge=rm.closest("[data-kind=\\"badge\\"]"); if(badge){badge.remove();return;} }',
    '  var tclose = e.target && e.target.closest ? e.target.closest("[data-kind=\\"tag\\"] [data-part=\\"tag-close\\"]") : null;',
    '  if(tclose){ var tag=tclose.closest("[data-kind=\\"tag\\"]"); if(tag){tag.remove();return;} }',
    '  var track = e.target && e.target.closest ? e.target.closest("[data-part=\\"track\\"]") : null;',
    '  if(track){',
    '    var sw = track.closest("[data-kind=\\"switch\\"],[data-kind=\\"toggle\\"]");',
    '    if(sw && sw.getAttribute("data-disabled")!=="true" && !track.hasAttribute("data-disabled")){',
    '      var on = sw.getAttribute("data-checked")!=="true";',
    '      sw.setAttribute("data-checked", on?"true":"false");',
    '      track.setAttribute("aria-checked", on?"true":"false");',
    '      dispatchPageEvent("changed", sw.getAttribute("data-entity")||"", sw, {checked:on});',
    '    }',
    '  }',
    '  // Number stepper buttons: clamp through min/max/step, mirror + report.',
    '  var stepper = e.target && e.target.closest ? e.target.closest("[data-part=\\"increment\\"],[data-part=\\"decrement\\"]") : null;',
    '  if(stepper){',
    '    var num = stepper.closest("[data-kind=\\"numberInput\\"]");',
    '    if(num && stepper.getAttribute("disabled")==null){',
    '      var cur = Number(num.getAttribute("data-value")||"0");',
    '      var mn = num.getAttribute("data-min"), mx = num.getAttribute("data-max");',
    '      var stp = 1;',
    '      var fld = num.querySelector("input[type=\\"number\\"]");',
    '      if(fld && fld.getAttribute("step")) stp = Number(fld.getAttribute("step")) || 1;',
    '      var nxt = cur + (stepper.getAttribute("data-part")==="increment" ? stp : -stp);',
    '      if(mn!==null && mn!=="") nxt = Math.max(Number(mn), nxt);',
    '      if(mx!==null && mx!=="") nxt = Math.min(Number(mx), nxt);',
    '      num.setAttribute("data-value", String(nxt));',
    '      if(fld) fld.value = String(nxt);',
    '      dispatchPageEvent("changed", num.getAttribute("data-entity")||"", num, {value:nxt});',
    '    }',
    '    return;',
    '  }',
    '  // Combobox option pick: mirror + close + report.',
    '  var copt = e.target && e.target.closest ? e.target.closest("[data-kind=\\"combobox\\"] [data-part=\\"option\\"]") : null;',
    '  if(copt && copt.getAttribute("data-disabled")==null){',
    '    var cb = copt.closest("[data-kind=\\"combobox\\"]");',
    '    var cv = copt.getAttribute("data-value")||"";',
    '    if(cb){',
    '      cb.setAttribute("data-value", cv);',
    '      var cs = cb.querySelector("input[data-part=\\"search\\"]");',
    '      if(cs){ cs.value = copt.textContent||cv; cs.setAttribute("aria-expanded","false"); }',
    '      var cp = cb.querySelector("[data-part=\\"panel\\"]");',
    '      if(cp) cp.setAttribute("hidden","");',
    '      var allc = cb.querySelectorAll("[data-part=\\"option\\"]");',
    '      for(var ci=0;ci<allc.length;ci++){ if(allc[ci]===copt) allc[ci].setAttribute("aria-selected","true"); else allc[ci].removeAttribute("aria-selected"); }',
    '      dispatchPageEvent("changed", cb.getAttribute("data-entity")||"", copt, {value:cv});',
    '      dispatchPageEvent("selected", cb.getAttribute("data-entity")||"", copt, {value:cv});',
    '    }',
    '    return;',
    '  }',
    '  // Rating star: paint up to the star + report.',
    '  var star = e.target && e.target.closest ? e.target.closest("[data-kind=\\"rating\\"] [data-part=\\"star\\"]") : null;',
    '  if(star && star.getAttribute("disabled")==null){',
    '    var rt = star.closest("[data-kind=\\"rating\\"]");',
    '    if(rt){',
    '      var rv = Number(star.getAttribute("data-star")||"0");',
    '      rt.setAttribute("data-value", String(rv));',
    '      var stars = rt.querySelectorAll("[data-part=\\"star\\"]");',
    '      for(var si=0;si<stars.length;si++){',
    '        var sn = Number(stars[si].getAttribute("data-star")||"0");',
    '        var on2 = sn<=rv;',
    '        stars[si].setAttribute("data-on", on2?"true":"false");',
    '        stars[si].setAttribute("aria-checked", on2?"true":"false");',
    '      }',
    '      dispatchPageEvent("changed", rt.getAttribute("data-entity")||"", star, {value:rv});',
    '    }',
    '    return;',
    '  }',
    '  // Tags remove buttons + editable preview + file browse.',
    '  var trem = e.target && e.target.closest ? e.target.closest("[data-kind=\\"tagsInput\\"] [data-part=\\"tag-remove\\"]") : null;',
    '  if(trem){',
    '    var tg = trem.closest("[data-part=\\"tag\\"]");',
    '    var th = trem.closest("[data-kind=\\"tagsInput\\"]");',
    '    if(tg && th){ tg.remove(); syncTags(th); }',
    '    return;',
    '  }',
    '  var edp = e.target && e.target.closest ? e.target.closest("[data-kind=\\"editable\\"] [data-part=\\"preview\\"]") : null;',
    '  if(edp){',
    '    var ed = edp.closest("[data-kind=\\"editable\\"]");',
    '    if(ed && ed.getAttribute("data-disabled")==null){ openEditable(ed); }',
    '    return;',
    '  }',
    '  var fbw = e.target && e.target.closest ? e.target.closest("[data-kind=\\"fileUpload\\"] [data-part=\\"browse\\"]") : null;',
    '  if(fbw){',
    '    var fh = fbw.closest("[data-kind=\\"fileUpload\\"]");',
    '    var fi = fh ? fh.querySelector("input[data-part=\\"file-input\\"]") : null;',
    '    if(fi) fi.click();',
    '    return;',
    '  }',
    '  // Tree caret toggles + label selects.',
    '  var caret = e.target && e.target.closest ? e.target.closest("[data-kind=\\"treeView\\"] [data-part=\\"caret\\"]") : null;',
    '  if(caret && caret.getAttribute("disabled")==null){',
    '    var tnode = caret.closest("[data-part=\\"node\\"]");',
    '    if(tnode){',
    '      var topen = tnode.getAttribute("data-expanded")!=="true";',
    '      tnode.setAttribute("data-expanded", topen?"true":"false");',
    '      caret.setAttribute("aria-expanded", topen?"true":"false");',
    '      var tkids = null;',
    '      for(var ti=0;ti<tnode.children.length;ti++){ if(tnode.children[ti].getAttribute && tnode.children[ti].getAttribute("data-part")==="children") tkids = tnode.children[ti]; }',
    '      if(tkids){ if(topen) tkids.removeAttribute("hidden"); else tkids.setAttribute("hidden",""); }',
    '      var tree = caret.closest("[data-kind=\\"treeView\\"]");',
    '      if(tree) dispatchPageEvent("changed", tree.getAttribute("data-entity")||"", caret, {key:tnode.getAttribute("data-node-key")||"",open:topen});',
    '    }',
    '    return;',
    '  }',
    '  var tlabel = e.target && e.target.closest ? e.target.closest("[data-kind=\\"treeView\\"] [data-part=\\"node-label\\"]") : null;',
    '  if(tlabel){',
    '    var tnode2 = tlabel.closest("[data-part=\\"node\\"]");',
    '    var tree2 = tlabel.closest("[data-kind=\\"treeView\\"]");',
    '    if(tnode2 && tree2){',
    '      var tkey = tnode2.getAttribute("data-node-key")||"";',
    '      var labels = tree2.querySelectorAll("[data-part=\\"node-label\\"]");',
    '      for(var li=0;li<labels.length;li++){ if(labels[li]===tlabel) labels[li].setAttribute("data-selected","true"); else labels[li].removeAttribute("data-selected"); }',
    '      dispatchPageEvent("selected", tree2.getAttribute("data-entity")||"", tlabel, {key:tkey});',
    '    }',
    '    return;',
    '  }',
    '  // Outside any combobox closes open panels.',
    '  if(!(e.target && e.target.closest && e.target.closest("[data-kind=\\"combobox\\"]"))){',
    '    var cps = document.querySelectorAll("[data-kind=\\"combobox\\"] [data-part=\\"panel\\"]:not([hidden])");',
    '    for(var cpi=0;cpi<cps.length;cpi++) cps[cpi].setAttribute("hidden","");',
    '  }',
    '});',
    'document.addEventListener("keydown", function(e){',
    '  if(e.key!==" "&&e.key!=="Enter")return;',
    '  var track = e.target && e.target.closest ? e.target.closest("[data-part=\\"track\\"][tabindex]") : null;',
    '  if(track){ e.preventDefault(); track.click(); }',
    '});',
    'document.addEventListener("keydown", function(e){',
    '  var pcell = e.target && e.target.closest ? e.target.closest("[data-kind=\\"pinInput\\"] input[data-part=\\"cell\\"]") : null;',
    '  if(!pcell) return;',
    '  if(e.key==="Backspace" && pcell.value !== "") return;',
    '  if(e.key==="Backspace" || e.key==="ArrowLeft" || e.key==="ArrowRight"){',
    '    e.preventDefault();',
    '    var pcl = Array.prototype.slice.call(pcell.closest("[data-kind=\\"pinInput\\"]").querySelectorAll("input[data-part=\\"cell\\"]"));',
    '    var tg = e.key==="ArrowRight" ? pcl[pcl.indexOf(pcell) + 1] : pcl[pcl.indexOf(pcell) - 1];',
    '    if(tg) tg.focus();',
    '  }',
    '});',
    'document.addEventListener("keydown", function(e){',
    '  var entry = e.target && e.target.closest ? e.target.closest("[data-kind=\\"tagsInput\\"] input[data-part=\\"entry\\"]") : null;',
    '  if(entry){',
    '    var th2 = entry.closest("[data-kind=\\"tagsInput\\"]");',
    '    if(e.key==="Enter" || e.key===","){',
    '      e.preventDefault();',
    '      var raw = entry.value.trim().replace(/,+$/,"");',
    '      if(raw !== "" && th2){',
    '        var tag = document.createElement("span");',
    '        tag.setAttribute("data-part","tag");',
    '        tag.setAttribute("data-tag", raw);',
    '        tag.textContent = raw;',
    '        var x = document.createElement("button");',
    '        x.setAttribute("type","button");',
    '        x.setAttribute("data-part","tag-remove");',
    '        x.setAttribute("aria-label","Remove");',
    '        x.textContent = "×";',
    '        tag.appendChild(x);',
    '        th2.insertBefore(tag, entry);',
    '        entry.value = "";',
    '        syncTags(th2);',
    '      }',
    '      return;',
    '    }',
    '    if(e.key==="Backspace" && entry.value === "" && th2){',
    '      var tags = th2.querySelectorAll("[data-part=\\"tag\\"]");',
    '      var last = tags[tags.length - 1];',
    '      if(last){ last.remove(); syncTags(th2); }',
    '    }',
    '    return;',
    '  }',
    '  var edf = e.target && e.target.closest ? e.target.closest("[data-kind=\\"editable\\"] input[data-part=\\"editor\\"]") : null;',
    '  if(edf){',
    '    var eh = edf.closest("[data-kind=\\"editable\\"]");',
    '    if(e.key==="Enter" && eh){ closeEditable(eh, true); }',
    '    else if(e.key==="Escape" && eh){ closeEditable(eh, false); }',
    '    return;',
    '  }',
    '  if(e.key==="Escape"){',
    '    var openPanels = document.querySelectorAll("[data-kind=\\"combobox\\"] [data-part=\\"panel\\"]:not([hidden])");',
    '    for(var pi=0;pi<openPanels.length;pi++) openPanels[pi].setAttribute("hidden","");',
    '  }',
    '});',
    'document.addEventListener("input", function(e){',
    '  var r2 = e.target && e.target.closest ? e.target.closest("[data-kind=\\"slider\\"] input[type=\\"range\\"]") : null;',
    '  if(r2){',
    '    var s3 = r2.closest("[data-kind=\\"slider\\"]");',
    '    if(s3){',
    '      var vv = Number(r2.value);',
    '      s3.setAttribute("data-value", String(vv));',
    '      var n3 = Number(s3.getAttribute("data-min")||"0"), x3 = Number(s3.getAttribute("data-max")||"100");',
    '      var p3 = x3>n3 ? ((vv-n3)/(x3-n3))*100 : 0;',
    '      var f3 = s3.querySelector("[data-part=\\"fill\\"]");',
    '      if(f3) f3.style.width = p3+"%";',
    '      var o3 = s3.querySelector("[data-part=\\"value\\"]");',
    '      if(o3) o3.textContent = String(vv);',
    '    }',
    '  }',
    '  // Pin cells: keep one char, advance on type; completion reports.',
    '  var cell = e.target && e.target.closest ? e.target.closest("[data-kind=\\"pinInput\\"] input[data-part=\\"cell\\"]") : null;',
    '  if(cell){',
    '    var pin = cell.closest("[data-kind=\\"pinInput\\"]");',
    '    if(pin && cell.getAttribute("disabled")==null){',
    '      if(cell.value.length > 1) cell.value = cell.value.slice(-1);',
    '      var cells = Array.prototype.slice.call(pin.querySelectorAll("input[data-part=\\"cell\\"]"));',
    '      if(cell.value !== "" ){',
    '        var nx = cells[cells.indexOf(cell) + 1];',
    '        if(nx) nx.focus();',
    '      }',
    '      var joined = cells.map(function(c){ return c.value }).join("");',
    '      pin.setAttribute("data-value", joined);',
    '      dispatchPageEvent("changed", pin.getAttribute("data-entity")||"", cell, {value:joined});',
    '      var full = joined.length === cells.length && cells.every(function(c){ return c.value !== "" });',
    '      if(full) dispatchPageEvent("complete", pin.getAttribute("data-entity")||"", cell, {value:joined});',
    '    }',
    '  }',
    '  // Combobox search filters options live and opens the panel.',
    '  var cs = e.target && e.target.closest ? e.target.closest("[data-kind=\\"combobox\\"] input[data-part=\\"search\\"]") : null;',
    '  if(cs){',
    '    var cx = cs.closest("[data-kind=\\"combobox\\"]");',
    '    if(cx){',
    '      var q = cs.value.toLowerCase();',
    '      var opts = cx.querySelectorAll("[data-part=\\"option\\"]");',
    '      for(var oi=0;oi<opts.length;oi++){',
    '        var ot = (opts[oi].textContent||"").toLowerCase();',
    '        if(ot.indexOf(q)>=0) opts[oi].removeAttribute("hidden"); else opts[oi].setAttribute("hidden","");',
    '      }',
    '      var cpanel = cx.querySelector("[data-part=\\"panel\\"]");',
    '      if(cpanel) cpanel.removeAttribute("hidden");',
    '      cs.setAttribute("aria-expanded","true");',
    '    }',
    '  }',
    '});',
    'document.addEventListener("change", function(e){',
    '  var el = e.target && e.target.closest ? e.target.closest("input[type=\\"checkbox\\"],input[type=\\"radio\\"]") : null;',
    '  if(el){ var host = el.closest("[data-entity]"); dispatchPageEvent("changed", host?host.getAttribute("data-entity"):"", el, {checked:!!el.checked,value:el.value}); }',
    '  // A select inside a form reports its value so FormHandle.getValue works.',
    '  var sel = e.target && e.target.closest ? e.target.closest("select") : null;',
    '  if(sel){ var fsel = sel.closest("[data-kind=\\"form\\"]"); dispatchPageEvent("changed", fsel?fsel.getAttribute("data-entity")||"":(sel.closest("[data-entity]")?sel.closest("[data-entity]").getAttribute("data-entity"):""), sel, { value: sel.value, name: sel.name||"" }); }',
    '  // A range drag repaints its host slider (fill, readout, mirror attr)',
    '  // then reports — the same paint the setValue method performs.',
    '  // A typed number mirrors onto its host the same way.',
    '  var nin = e.target && e.target.closest ? e.target.closest("[data-kind=\\"numberInput\\"] input[type=\\"number\\"]") : null;',
    '  if(nin){',
    '    var nh = nin.closest("[data-kind=\\"numberInput\\"]");',
    '    if(nh){ nh.setAttribute("data-value", nin.value); dispatchPageEvent("changed", nh.getAttribute("data-entity")||"", nh, {value:Number(nin.value)}); }',
    '  }',
    '  var rng = e.target && e.target.closest ? e.target.closest("[data-kind=\\"slider\\"] input[type=\\"range\\"]") : null;',
    '  if(rng){',
    '    var sw2 = rng.closest("[data-kind=\\"slider\\"]");',
    '    if(sw2 && sw2.getAttribute("data-disabled")!=="true"){',
    '      var v = Number(rng.value);',
    '      sw2.setAttribute("data-value", String(v));',
    '      var mn = Number(sw2.getAttribute("data-min")||"0"), mx = Number(sw2.getAttribute("data-max")||"100");',
    '      var pc = mx>mn ? ((v-mn)/(mx-mn))*100 : 0;',
    '      var fl = sw2.querySelector("[data-part=\\"fill\\"]");',
    '      if(fl) fl.style.width = pc+"%";',
    '      var vo = sw2.querySelector("[data-part=\\"value\\"]");',
    '      if(vo) vo.textContent = String(v);',
    '      dispatchPageEvent("changed", sw2.getAttribute("data-entity")||"", sw2, {value:v});',
    '    }',
    '  }',
    '  // File picks paint the list + report (names/sizes only — contents stay local).',
    '  var fin = e.target && e.target.closest ? e.target.closest("[data-kind=\\"fileUpload\\"] input[data-part=\\"file-input\\"]") : null;',
    '  if(fin){',
    '    var fup = fin.closest("[data-kind=\\"fileUpload\\"]");',
    '    if(fup){ var fs = paintFiles(fup); dispatchPageEvent("changed", fup.getAttribute("data-entity")||"", fin, {files:fs}); }',
    '  }',
    '});',
    'document.addEventListener("focusout", function(e){',
    '  var edf = e.target && e.target.closest ? e.target.closest("[data-kind=\\"editable\\"] input[data-part=\\"editor\\"]") : null;',
    '  if(edf){ var eh = edf.closest("[data-kind=\\"editable\\"]"); if(eh) closeEditable(eh, true); }',
    '});',
  ];
}
