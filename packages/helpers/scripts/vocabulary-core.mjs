// Generate vocabulary.json: every word of `make(…)` and `set(…)`, how it is
// said, and what value it takes — read from the methods' own signatures and
// doc comments, plus src/say.ts. Languages that write helpers code (Godtongue)
// read this file instead of keeping their own list, so a new helpers word is a
// new language word with no change there.
//
// The command is scripts/vocabulary.mjs; this module only generates.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import ts from 'typescript'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { SAY, BARE } = await import(pathToFileURL(path.join(root, 'src', 'say.ts')).href)

/** "textColor" → "text color". */
const spoken = (name) => name.replace(/([a-z])([A-Z])/g, '$1 $2').toLowerCase()
/** Both spellings of colour. */
const spellings = (phrase) => [...new Set([phrase, phrase.replace(/\bcolor\b/g, 'colour'), phrase.replace(/\bcolour\b/g, 'color')])]

function describeParam(param, checker) {
  const name = param.name.getText()
  const typeText = param.type ? param.type.getText() : ''
  const optional = !!param.questionToken || !!param.initializer
  const type = checker.getTypeAtLocation(param)
  const members = type.isUnion() ? type.types : [type]
  const words = []
  let number = false
  let text = false
  for (const m of members) {
    if (m.isStringLiteral()) words.push(m.value)
    else if (m.flags & ts.TypeFlags.NumberLike) number = true
    else if (m.flags & ts.TypeFlags.StringLike) text = true
    else if (m.flags & ts.TypeFlags.Intersection) text = true   // string & {}: any string
    else if (m.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown)) text = true
  }
  const out = { name, ...(optional ? { optional: true } : {}) }
  if (/^colou?r$/i.test(name)) return { ...out, takes: 'colour' }
  if (words.length) {
    const amount = /\bTextSize\b/.test(typeText) ? 'text' : /\b(Size|Length)\b/.test(typeText) ? 'distance' : undefined
    return { ...out, takes: 'words', words, ...(amount ? { amount } : {}), ...(number && !amount ? { number: true } : {}) }
  }
  if (number && !text) return { ...out, takes: 'number' }
  if (text && !number) return { ...out, takes: 'text' }
  return { ...out, takes: 'value' }
}

function methodsOf(file, className, returns, checker, program) {
  const sf = program.getSourceFile(file)
  const out = {}
  const visit = (node) => {
    if (ts.isClassDeclaration(node) && node.name?.text === className) {
      for (const m of node.members) {
        if (!ts.isMethodDeclaration(m) || !m.name || !ts.isIdentifier(m.name)) continue
        const mods = ts.getModifiers(m) ?? []
        if (mods.some((x) => x.kind === ts.SyntaxKind.PrivateKeyword || x.kind === ts.SyntaxKind.ProtectedKeyword || x.kind === ts.SyntaxKind.StaticKeyword)) continue
        if (!m.type || !returns.includes(m.type.getText())) continue
        const name = m.name.text
        const doc = ts.getJSDocCommentsAndTags(m).map((d) => (typeof d.comment === 'string' ? d.comment : '')).join(' ').trim()
        const say = [...new Set([spoken(name), ...(SAY[name] ?? [])].flatMap(spellings))]
        out[name] = {
          say,
          params: m.parameters.map((p) => describeParam(p, checker)),
          ...(m.type.getText() !== 'this' ? { scope: true } : {}),
          ...(doc ? { doc: doc.replace(/\s+/g, ' ').split(/(?<=\.)\s/)[0] } : {}),
        }
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(sf)
  return out
}

export function generate() {
  const files = [path.join(root, 'src', 'make.ts'), path.join(root, 'src', 'set.ts')]
  const program = ts.createProgram(files, { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, strict: true, noEmit: true, skipLibCheck: true })
  const checker = program.getTypeChecker()
  const make = methodsOf(files[0], 'Make', ['this', 'Make'], checker, program)
  const set = methodsOf(files[1], 'SetTo', ['this'], checker, program)
  const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)))
  return JSON.stringify({
    about: 'Generated by @studiomorgana/helpers scripts/vocabulary.mjs — do not edit. The words of make(…) and set(…), how they are said, and what they take.',
    make: sorted(make),
    set: sorted(set),
    bare: BARE,
  }, null, 2) + '\n'
}

