/**
 * ejectProject — compile the Morgana app, then emit a plain React + Express
 * codebase with no framework trace. The grep gate fails the run if any
 * trace survives; the report lists every manual adaptation.
 */
import fs from 'node:fs';
import path from 'node:path';
import { compileProject } from '@morgana/sdk-compile';
import type { EjectSelection, EjectReport } from './core/types';
import { createReport, printReport } from './core/types';
import { grepGate } from './core/grep-gate';
import { collectServerActions, emitExpress } from './express/emit';
import { collectClientActions, emitReactApp } from './react/emit';

export type { EjectSelection, EjectReport };
export { printReport } from './core/types';

function fullSelection(sel: EjectSelection): Required<EjectSelection> {
  return {
    pages: sel.pages ?? [],
    port: sel.port ?? 3001,
    apiPrefix: sel.apiPrefix ?? '/api',
    dbPath: sel.dbPath ?? 'data/app.sqlite',
    seed: sel.seed ?? true,
    auth: sel.auth ?? 'session-sqlite',
    cron: sel.cron ?? true,
  };
}

export async function ejectProject(opts: {
  dir: string;
  outDir: string;
  selection?: EjectSelection;
}): Promise<EjectReport> {
  const dir = path.resolve(opts.dir);
  const outDir = path.resolve(opts.outDir);
  const sel = fullSelection(opts.selection ?? {});
  const report = createReport(outDir);

  // 1. Compile — the IR is the source of truth for structure.
  const compiled = await compileProject({ dir, outDir: path.join(dir, 'dist') });
  const ir = compiled.ir;
  if (sel.pages && sel.pages.length) {
    for (const p of sel.pages) {
      if (!ir.pages.has(p)) throw new Error(`eject: unknown page "${p}"`);
    }
  } else {
    sel.pages = [...ir.pages.keys()];
  }
  const dist = path.join(dir, 'dist');
  const readJson = (rel: string, fallback: unknown): any => {
    try {
      return JSON.parse(fs.readFileSync(path.join(dist, rel), 'utf8'));
    } catch {
      return fallback;
    }
  };
  const stores = readJson('server/stores.json', []);
  const triggers = readJson('server/triggers.json', []);
  const styleCss = fs.readFileSync(path.join(dist, 'assets', 'style.css'), 'utf8');

  // 2. Collect + emit both sides.
  const serverActions = collectServerActions(dir);
  const clientActions = collectClientActions(dir);
  const serverActionRefs = serverActions.map((a) => ({ name: a.name, domain: a.domain }));
  const backend = emitExpress(dir, serverActions, stores, triggers, sel, report.fallbacks);
  const frontend = emitReactApp(ir, clientActions, serverActionRefs, styleCss, sel, report);

  // 3. Write files.
  const write = (rel: string, content: string): void => {
    const full = path.join(outDir, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content, 'utf8');
    report.files.push(rel);
  };
  for (const [rel, content] of Object.entries({ ...backend.files, ...frontend.files })) write(rel, content);

  // 4. Stylesheet: verbatim content, neutral name + neutral keyframes. The
  // generated-by header names the framework, so it is stripped — the content
  // is plain CSS either way.
  const css = styleCss
    .replace(/\/\*\s*generated by @morgana\/sdk-compile\s*\*\/\n?/, '')
    .replace(/morgana-/g, 'ui-');
  write('client/src/index.css', css);

  // 5. Root package + README.
  write(
    'package.json',
    JSON.stringify(
      { name: 'ejected-app', private: true, version: '1.0.0', workspaces: ['client', 'server'], scripts: { dev: 'npm run dev --workspaces', build: 'npm run build --workspaces' } },
      null, 2,
    ) + '\n',
  );
  write(
    'README.md',
    `# App\n\nPlain React + Express, ejected.\n\n- \`npm install\` then \`npm run dev\` (client :5173 proxies /api to server :${sel.port}).\n- Server: \`cd server && npm run dev\`. Client: \`cd client && npm run dev\`.\n- Database: \`server/${sel.dbPath}\` (SQLite). Schema in \`server/src/db/schema.sql\`.\n`,
  );

  report.ejected.pages = frontend.pages;
  report.ejected.actions = backend.actions;
  report.ejected.stores = stores.map((s: any) => s.name);
  report.ejected.routes = backend.routes;

  // 6. Grep gate — zero trace, enforced.
  const violations = grepGate(outDir);
  if (violations.length) {
    throw new Error(`eject failed the zero-trace gate:\n${violations.map((v) => `  ${v}`).join('\n')}`);
  }
  return report;
}
